import { roundMoney } from "@/lib/currency";

/**
 * Original shop catalog inspired by popular laser-cut plywood categories
 * (Etsy / handmade marketplaces). Names, copy and SKUs are original —
 * not scraped or copied from third-party listings.
 *
 * Draft amounts are authored in EUR (shop display currency).
 * Every size fits a laser bed of max 35×35 cm. Each product has 3 sizes
 * with market-based prices for the Bulgarian craft market.
 */

export type SeedLaserType = "ENGRAVE" | "CUT" | "BOTH";

export type SeedOption = {
  label: string;
  sizeLabel: string;
  thicknessMm: number;
  laserType: SeedLaserType;
  material: string;
  finish: string;
  doubleSided: boolean;
  priceModifier: number;
};

export type SeedProduct = {
  name: string;
  slug: string;
  category: string;
  description: string;
  basePrice: number;
  imageUrl: string;
  galleryUrls: string[];
  options: SeedOption[];
};

function imgs(slug: string): { imageUrl: string; galleryUrls: string[] } {
  const photo = `/products/photos/${slug}.png`;
  return { imageUrl: photo, galleryUrls: [photo] };
}

function opts(
  variants: Array<{
    label: string;
    sizeLabel: string;
    thicknessMm: number;
    laserType: SeedLaserType;
    material?: string;
    finish?: string;
    doubleSided?: boolean;
    priceModifier: number;
  }>,
): SeedOption[] {
  return variants.map((v) => ({
    material: v.material ?? "birch-plywood",
    finish: v.finish ?? "raw",
    doubleSided: v.doubleSided ?? false,
    ...v,
  }));
}

type Draft = {
  name: string;
  slug: string;
  category: string;
  description: string;
  basePrice: number;
  options: SeedOption[];
};

function pack(drafts: Draft[]): SeedProduct[] {
  return drafts.map((d) => ({
    ...d,
    basePrice: roundMoney(d.basePrice),
    options: d.options.map((o) => ({
      ...o,
      priceModifier: roundMoney(o.priceModifier),
    })),
    ...imgs(d.slug),
  }));
}

