export function giftGuideBySlug(slug: string): GiftGuide | undefined {
  return GIFT_GUIDES.find((g) => g.slug === slug);
}

/** Canonical blog URL */
export function giftGuidePath(slug: string): string {
  return `/blog/${slug}`;
}

export function blogIndexPath(): string {
  return "/blog";
}

/** Newest first for blog index and sitemap freshness. */
export function giftGuidesNewestFirst(): GiftGuide[] {
  return [...GIFT_GUIDES].sort((a, b) =>
    a.publishedAt < b.publishedAt ? 1 : a.publishedAt > b.publishedAt ? -1 : 0,
  );
}
