export function categoryLandingBySlug(
  slug: string,
): CategoryLanding | undefined {
  return CATEGORY_LANDINGS.find((c) => c.slug === slug);
}

export function categoryLandingById(
  categoryId: string,
): CategoryLanding | undefined {
  return CATEGORY_LANDINGS.find((c) => c.categoryId === categoryId);
}

export function categoryLandingPath(slug: string): string {
  return `/kategoriya/${slug}`;
}

export function allCategoryLandingSlugs(): string[] {
  return CATEGORY_LANDINGS.map((c) => c.slug);
}

/** Fallback unique meta when no dedicated landing exists. */
export function genericCategoryMeta(categoryId: string): {
  title: string;
  description: string;
} | null {
  const cat = categoryById(categoryId as CategoryId);
  if (!cat || cat.id === "other") return null;
  return {
    title: `${cat.label} — персонализирани подаръци с гравиране`,
    description: `Персонализирани продукти в категория „${cat.label}“ от Studio Breza — гравиране по име и послание, ясна цена и доставка в цяла България.`,
  };
}
